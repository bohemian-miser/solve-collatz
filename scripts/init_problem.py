#!/usr/bin/env python3
"""Initialize a fresh solve-anything instance for any Lean 4 conjecture in one command.

Usage:
  python3 scripts/init_problem.py \
    --name solve-goldbach \
    --title "Goldbach Conjecture" \
    --lean-root Goldbach \
    --namespace SolveGoldbach \
    --tagline "Every even integer > 2 is the sum of two primes."
"""

from __future__ import annotations

import argparse
import pathlib
import shutil
import sys


def main() -> int:
    p = argparse.ArgumentParser(description="Bootstrap a solve-anything repo for a new Lean 4 conjecture")
    p.add_argument("--name", required=True, help="Repository/package name (e.g. solve-goldbach)")
    p.add_argument("--title", required=True, help="Human-readable conjecture title")
    p.add_argument("--lean-root", required=True, help="Top-level Lean library folder (e.g. Goldbach)")
    p.add_argument("--namespace", required=True, help="Lean namespace (e.g. SolveGoldbach)")
    p.add_argument("--tagline", default="Lean 4 kernel-verified dual-track (Prove + Disprove) crowd-swarm.")
    args = p.parse_args()

    lean_root = args.lean_root
    ns = args.namespace

    if lean_root != "Problem" and pathlib.Path("Problem").exists() and not pathlib.Path(lean_root).exists():
        shutil.move("Problem", lean_root)
    if lean_root != "Problem" and pathlib.Path("Problem.lean").exists():
        pathlib.Path("Problem.lean").unlink()

    pathlib.Path("problem.toml").write_text(
        f"""# Generated by scripts/init_problem.py — freeze on main after dropping in Challenge.lean.

[problem]
name = "{args.name}"
title = "{args.title}"
tagline = "{args.tagline}"
lean_root = "{lean_root}"
namespace = "{ns}"
challenge_file = "Challenge.lean"
conjecture_decl = "{ns}.Conjecture"
disproof_decl = "{ns}.Disproof"

[guards]
max_line_length = 100
max_file_lines = 1000
max_proof_lines = 50
frozen_files = [
  "Challenge.lean",
  "problem.toml",
  "lean-toolchain",
  "scripts/audit_axioms.py",
  "scripts/check_challenge_frozen.py",
  "scripts/check_source_guards.py",
  ".github/workflows/verify.yml",
  ".github/workflows/claims.yml",
  ".github/workflows/dashboard.yml",
  ".github/workflows/label-pr.yml",
]

[search]
ci_hook = "search/ci_checks.sh"
""",
        encoding="utf-8",
    )

    pathlib.Path("lakefile.toml").write_text(
        f"""name = "{args.name}"
version = "0.1.0"
defaultTargets = ["Challenge", "{lean_root}"]

[leanOptions]
warningAsError = true
autoImplicit = false
relaxedAutoImplicit = false

[[lean_lib]]
name = "Challenge"

[[lean_lib]]
name = "{lean_root}"
""",
        encoding="utf-8",
    )

    pathlib.Path(f"{lean_root}.lean").write_text(
        f"""/-
Copyright (c) 2026 The {args.name} contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
-/
module

public import Challenge
public import {lean_root}.Core.Basic
public import {lean_root}.Disprove.Cert
""",
        encoding="utf-8",
    )

    for rel in [
        "Challenge.lean",
        f"{lean_root}/Core/Basic.lean",
        f"{lean_root}/Disprove/Cert.lean",
    ]:
        fp = pathlib.Path(rel)
        if fp.exists():
            txt = fp.read_text(encoding="utf-8")
            txt = txt.replace("import Problem", f"import {lean_root}")
            txt = txt.replace("namespace Problem", f"namespace {ns}")
            txt = txt.replace("end Problem", f"end {ns}")
            txt = txt.replace("Problem.", f"{ns}.")
            fp.write_text(txt, encoding="utf-8")

    print(
        f"Initialized `{args.name}` ({lean_root}/, namespace `{ns}`).\n"
        f"Next steps:\n"
        f"  1. Edit `Challenge.lean` with your exact Lean 4 conjecture.\n"
        f"  2. Update `frontier/FRONTIER.toml` and `frontier/BARRIERS.md`.\n"
        f"  3. Run `python3 scripts/check_all.py`."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
