#!/usr/bin/env python3
"""Generate kernel range-check files under `Collatz/Known/Range/` (RANGE-001/002).

Each shell `[2^s, 2^(s+1))` is split into buckets of residues mod `2^12`, balanced by the number
of leaves `rangeWalk` will check (counted by `shell_profile.c`, which walks the same tree). Each
bucket is one `decide +kernel` theorem in its own module `Range/S<s>/B<i>.lean`, so Lake checks
buckets in parallel; `Range/Shell<s>.lean` joins them with a balanced tree of `shellCovers_merge`. `Collatz/Known/Range.lean` chains the shells onto the `2^22` range from EliahouLifted22.

Usage:
  python3 search/range_cert/gen_shells.py --to 28              # shells 22..27, range 2^28
  python3 search/range_cert/gen_shells.py --to 32 --bucket-leaves 40000
  python3 search/range_cert/gen_shells.py --self-test           # profiler vs Python model
"""

from __future__ import annotations

import argparse
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent))

from engine import compile_c, run_json_engine  # noqa: E402

T_BITS = 12  # bucket key: n % 2^12 (rangeTop with top = 11)
BASE = 22  # EliahouLifted22 already covers n < 2^22
OUT_DIR = REPO_ROOT / "Collatz" / "Known" / "Range"
HEADER = """/-
Copyright (c) 2026 The solve-collatz contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
-/
module
"""


def profile(s: int) -> dict:
    binary = compile_c("solve_collatz_shell_profile", HERE / "shell_profile.c")
    return run_json_engine(binary, [str(s), str(T_BITS)])["canonical"]


def buckets(leaves: list[int], target: int) -> list[int]:
    """Boundaries 0 = b0 < b1 < ... < bm = 2^T with about `target` leaves per bucket."""
    bounds, acc = [0], 0
    for r, count in enumerate(leaves):
        acc += count
        if acc >= target and r + 1 < len(leaves):
            bounds.append(r + 1)
            acc = 0
    bounds.append(len(leaves))
    return bounds


def bucket_file(s: int, i: int, lo: int, hi: int, fuel: int, leaves: int) -> str:
    """One bucket per module, so Lake checks the buckets of a shell in parallel."""
    return "\n".join([
        HEADER, "public import Collatz.Known.RangeCheck", "",
        "/-! Generated by `search/range_cert/gen_shells.py`; do not edit by hand.",
        f"Shell `[2^{s}, 2^{s + 1})`, residues `{lo} ≤ n % 2^{T_BITS} < {hi}`: {leaves} leaves. -/",
        "", "public section", "", "namespace SolveCollatz.Range", "",
        f"/-- Bucket {i} of shell `2^{s}`. -/",
        f"theorem shell{s}_b{i} : ShellCovers {s} {T_BITS} {lo} {hi} :=",
        f"  shellCovers_of_check (fuel := {fuel}) (rem := {s - T_BITS}) (top := 11)"
        " (by decide +kernel)",
        "", "end SolveCollatz.Range", "", "end", ""])


def shell_file(s: int, prof: dict, bounds: list[int]) -> str:
    """Merge the bucket modules of shell `s` with a balanced tree of `shellCovers_merge`."""
    name = f"shell{s}"
    nb = len(bounds) - 1
    lines = [HEADER] + [f"public import Collatz.Known.Range.S{s}.B{i}" for i in range(nb)]
    lines += ["", "/-! Generated by `search/range_cert/gen_shells.py`; do not edit by hand.",
              f"Shell `[2^{s}, 2^{s + 1})`: {prof['total_leaves']} leaves in {nb}"
              f" buckets of `n % 2^{T_BITS}`. -/", "",
              "public section", "", "namespace SolveCollatz.Range", ""]
    level = [(f"{name}_b{i}", lo, hi) for i, (lo, hi) in enumerate(zip(bounds, bounds[1:]))]
    depth = 0
    while len(level) > 1:
        nxt = []
        for j in range(0, len(level), 2):
            if j + 1 == len(level):
                nxt.append(level[j])
                continue
            (a, lo, _), (b, _, hi) = level[j], level[j + 1]
            nm = f"{name}_m{depth}_{j // 2}"
            lines.append(f"/-- Buckets `{lo} ≤ n % 2^{T_BITS} < {hi}` of shell `2^{s}`. -/")
            lines.append(f"theorem {nm} : ShellCovers {s} {T_BITS} {lo} {hi} :=")
            lines.append(f"  shellCovers_merge {a} {b}")
            nxt.append((nm, lo, hi))
        level, depth = nxt, depth + 1
    lines += ["", f"/-- Every `n` in `[2^{s}, 2^{s + 1})` has finite stopping time. -/",
              f"theorem {name} : ∀ n : Nat, 2 ^ {s} ≤ n → n < 2 ^ {s + 1} →"
              " HasFiniteStoppingTime n :=",
              f"  shell_of_covers (by decide) {level[0][0]}", "",
              "end SolveCollatz.Range", "", "end", ""]
    return "\n".join(lines)


def range_file(top: int) -> str:
    lines = [HEADER, "public import Collatz.Known.RangeCheck"]
    lines += [f"public import Collatz.Known.Range.Shell{s}" for s in range(BASE, top)]
    lines += ["", "/-! Generated by `search/range_cert/gen_shells.py`; do not edit by hand.",
              f"Kernel-checked finite stopping time for every `2 ≤ n < 2^{top}`. -/", "",
              "public section", "", "namespace SolveCollatz.Range", ""]
    prev = "finiteStoppingTime_lt_two_pow_22"
    for s in range(BASE, top):
        cur = f"finiteStoppingTime_lt_two_pow_{s + 1}"
        lines.append(f"/-- Every `2 ≤ n < 2^{s + 1}` has finite stopping time. -/")
        lines.append(f"theorem {cur} :")
        lines.append(f"    ∀ n : Nat, 2 ≤ n → n < 2 ^ {s + 1} → HasFiniteStoppingTime n :=")
        lines.append(f"  finiteStoppingTime_extend {prev} shell{s}")
        lines.append("")
        prev = cur
    lines += ["end SolveCollatz.Range", "", "end", ""]
    return "\n".join(lines)


def self_test() -> int:
    """The profiler must count the same leaves as a direct Python walk of the Lean tree."""
    def pruned(r, cur, p3, p2):
        return p3 < p2 and cur + p3 < r + p2

    def walk(depth, s, r, cur, p3, p2, out):
        if depth == s:
            if not pruned(r, cur, p3, p2):
                out[r % (1 << T_BITS)] = out.get(r % (1 << T_BITS), 0) + 1
            return
        if pruned(r, cur, p3, p2):
            return
        p2n, cp3, rp2 = 2 * p2, cur + p3, r + p2
        if cur % 2:
            walk(depth + 1, s, r, (3 * cur + 1) // 2, 3 * p3, p2n, out)
            walk(depth + 1, s, rp2, cp3 // 2, p3, p2n, out)
        else:
            walk(depth + 1, s, r, cur // 2, p3, p2n, out)
            walk(depth + 1, s, rp2, (3 * cp3 + 1) // 2, 3 * p3, p2n, out)

    for s in (14, 18):
        py: dict[int, int] = {}
        walk(1, s, 1, 2, 3, 2, py)
        c = profile(s)["leaves"]
        if any(c[r] != py.get(r, 0) for r in range(1 << T_BITS)):
            print(f"FAIL: shell_profile disagrees with Python walk at s={s}", file=sys.stderr)
            return 1
    print("PASS: shell_profile matches the Python model of rangeWalk (s = 14, 18).")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--to", type=int, help="generate shells 22..TO-1, proving the range 2^TO")
    ap.add_argument("--bucket-leaves", type=int, default=25000, help="leaves per bucket")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if not args.to or args.to <= BASE:
        ap.error(f"--to must be > {BASE}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for s in range(BASE, args.to):
        prof = profile(s)
        bounds = buckets(prof["leaves"], args.bucket_leaves)
        fuel = prof["max_iters"] + 4
        bdir = OUT_DIR / f"S{s}"
        bdir.mkdir(parents=True, exist_ok=True)
        for old in bdir.glob("B*.lean"):
            old.unlink()
        for i, (lo, hi) in enumerate(zip(bounds, bounds[1:])):
            text = bucket_file(s, i, lo, hi, fuel, sum(prof["leaves"][lo:hi]))
            (bdir / f"B{i}.lean").write_text(text, encoding="utf-8")
        (OUT_DIR / f"Shell{s}.lean").write_text(shell_file(s, prof, bounds), encoding="utf-8")
        print(f"Shell{s}.lean: {prof['total_leaves']} leaves, {len(bounds) - 1} buckets,"
              f" fuel {prof['max_iters'] + 4}")
    (OUT_DIR.parent / "Range.lean").write_text(range_file(args.to), encoding="utf-8")
    print(f"Range.lean: chains shells up to 2^{args.to}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
